// Painting pipeline. Source of truth: paintings-src/*.jpg (full-size originals, tracked in git, NOT deployed).
// Output: public/paintings/<name>-<width>.webp at several widths (deployed), plus
//   src/paintingsData.js  -> { "<name>.jpg": { w, h, widths: [...] } }  (dims drive gallery sizing, widths drive src selection)
//   src/colorsData.js     -> { "<name>.jpg": [[r,g,b] x6] }             (dominant palette for cohesive ordering + placeholders)
// Incremental: a variant is re-encoded only if missing or older than its source. Orphaned variants are removed.
// Run: npm run paintings   (then npm run build)
const sharp = require('sharp')
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const SRC = path.join(ROOT, 'paintings-src')
const OUT = path.join(ROOT, 'public', 'paintings')
const WIDTHS = [480, 800, 1200, 1800]
const QUALITY = { 480: 80, 800: 80, 1200: 78, 1800: 76 }

fs.mkdirSync(OUT, { recursive: true })

;(async () => {
  const files = fs.readdirSync(SRC).filter((f) => /\.jpe?g$/i.test(f)).sort()
  const dims = {}, colors = {}, expected = new Set()
  let encoded = 0
  for (const f of files) {
    const base = f.replace(/\.jpe?g$/i, '')
    const inPath = path.join(SRC, f)
    const meta = await sharp(inPath, { failOn: 'none' }).metadata()
    const rotated = meta.orientation >= 5
    const W = rotated ? meta.height : meta.width, H = rotated ? meta.width : meta.height
    // every standard width below the source width, plus the largest (source width, capped at 1800) — never upscale
    const widths = WIDTHS.filter((w) => w < W)
    const top = Math.min(W, 1800)
    if (!widths.includes(top)) widths.push(top)
    for (const w of widths) {
      const out = path.join(OUT, `${base}-${w}.webp`)
      expected.add(path.basename(out))
      const stale = !fs.existsSync(out) || fs.statSync(out).mtimeMs < fs.statSync(inPath).mtimeMs
      if (stale) {
        await sharp(inPath, { failOn: 'none' }).rotate().resize({ width: w, withoutEnlargement: true })
          .webp({ quality: QUALITY[w] || 76, effort: 5 }).toFile(out)
        encoded++
      }
    }
    dims[f] = { w: W, h: H, widths }
    // dominant palette: 56x56 downsample, 8 levels per channel, top 6 bins by count
    const { data } = await sharp(inPath, { failOn: 'none' }).rotate().resize(56, 56, { fit: 'fill' }).removeAlpha().raw().toBuffer({ resolveWithObject: true })
    const bins = {}
    for (let i = 0; i < data.length; i += 3) {
      const r = data[i], g = data[i + 1], b = data[i + 2]
      const k = `${r >> 5},${g >> 5},${b >> 5}`
      const o = bins[k] || (bins[k] = { n: 0, r: 0, g: 0, b: 0 })
      o.n++; o.r += r; o.g += g; o.b += b
    }
    colors[f] = Object.values(bins).sort((a, b) => b.n - a.n).slice(0, 6)
      .map((o) => [Math.round(o.r / o.n), Math.round(o.g / o.n), Math.round(o.b / o.n)])
    process.stdout.write('.')
  }
  for (const f of fs.readdirSync(OUT)) if (!expected.has(f)) { fs.unlinkSync(path.join(OUT, f)); console.log('\nremoved orphan', f) }
  fs.writeFileSync(path.join(ROOT, 'src', 'paintingsData.js'),
    '// AUTO-GENERATED by scripts/build-paintings.cjs — source pixel dims + available WebP widths (public/paintings/<name>-<w>.webp)\nexport default ' + JSON.stringify(dims) + '\n')
  fs.writeFileSync(path.join(ROOT, 'src', 'colorsData.js'),
    '// AUTO-GENERATED by scripts/build-paintings.cjs — top 6 dominant colors [r,g,b] per painting\nexport default ' + JSON.stringify(colors) + '\n')
  const outFiles = fs.readdirSync(OUT)
  const total = outFiles.reduce((s, x) => s + fs.statSync(path.join(OUT, x)).size, 0)
  console.log(`\n${files.length} paintings, ${encoded} variants encoded -> ${outFiles.length} webp files, ${(total / 1048576).toFixed(1)} MB total`)
})().catch((e) => { console.error(e); process.exit(1) })
